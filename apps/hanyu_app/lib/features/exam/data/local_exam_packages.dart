LocalExamQuestion _build(
  _Draft draft,
  int level,
  int index,
  ExamSection section,
) {
  final position = (index + level) % 4;
  final pool = [draft.answer, ...draft.other];
  return LocalExamQuestion(
    id: 'draft-$level-${section.name}-$index',
    section: section,
    prompt: draft.prompt,
    choices: List.generate(4, (i) => pool[(i - position + 4) % 4]),
    correct: position,
    explanation: draft.explanation,
    transcript: draft.transcript,
  );
}


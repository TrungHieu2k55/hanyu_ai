      sourceRef: 'Hanyu original draft, 2026-11-19; language review pending',
      questions: [
        for (var i = 0; i < 10; i++)
          _build(_listening[level - 1][i], level, i, ExamSection.listening),
        for (var i = 0; i < 10; i++)
          _build(_reading[level - 1][i], level, i, ExamSection.reading),
      ],
    ),
]);
